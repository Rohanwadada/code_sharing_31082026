'use client';

import React, { useState } from 'react';
import classes from './ReviewCompetencies.module.css';
import { useRouter } from 'next/navigation';
import {
  assessmentFormationSourceType,
  useAssessmentFormationStore,
} from '@/store/assessmentFormationStore';
import { createAssessment } from '@/service/assessment.service';
import { useEffect } from 'react';
import Image from 'next/image';
import aiInterView from '@/assets/assessment/ai-interview.svg';
import { useProjectStore } from '@/store/projectStore';

const InfoIcon = () => (
  <svg
    className={classes.infoIcon}
    width="14"
    height="14"
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    strokeWidth="2"
    strokeLinecap="round"
    strokeLinejoin="round"
  >
    <circle cx="12" cy="12" r="10"></circle>
    <line x1="12" y1="16" x2="12" y2="12"></line>
    <line x1="12" y1="8" x2="12.01" y2="8"></line>
  </svg>
);

const ReviewCompetencies = ({ projectId }) => {
  const projectName = useProjectStore((s) => s.currentProjectName);

  const setAssessmentFormationId = useAssessmentFormationStore(
    (s) => s.setAssessmentFormationId,
  );
  const assessmentFormationDetails = useAssessmentFormationStore(
    (s) => s.assessmentFormationDetails,
  );
  const setAssessmentFormationDetails = useAssessmentFormationStore(
    (s) => s.setAssessmentFormationDetails,
  );
  const assessmentFormationSource = useAssessmentFormationStore(
    (s) => s.assessmentFormationSource,
  );

  const isAiGenerated =
    assessmentFormationSource === assessmentFormationSourceType.AI_GENERATE ||
    assessmentFormationSource === 'ai generated' ||
    (typeof assessmentFormationSource === 'string' &&
      assessmentFormationSource.toLowerCase().includes('ai'));

  const sourceSubLabel = isAiGenerated ? 'Generated By AI' : 'Uploaded By Own';

  const [tableData, setTableData] = useState(
    assessmentFormationDetails?.items || [],
  );
  const [initialSummary, setInitialSummary] = useState(
    assessmentFormationDetails?.summary || {},
  );
  const [summary, setSummary] = useState(
    assessmentFormationDetails?.summary || {},
  );
  const [isActiveApiCall, setIsActiveApiCall] = useState(false);

  const router = useRouter();

  console.log(assessmentFormationSource);

  const handleLevelChange = (idx, newLevel) => {
    setTableData((prev) =>
      prev.map((row, index) =>
        index === idx ? { ...row, priority: newLevel } : row,
      ),
    );

    // enable the sub_competency as a side effect
    setTableData((prev) =>
      prev.map((row, index) =>
        index === idx ? { ...row, add_to_test: true } : row,
      ),
    );
  };

  const handleToggleActive = (idx) => {
    setTableData((prev) =>
      prev.map((row, index) =>
        index === idx ? { ...row, add_to_test: !row.add_to_test } : row,
      ),
    );
  };

  const handleProceedClick = async () => {
    setIsActiveApiCall(true);
    try {
      const data = {
        items: tableData,
        source: assessmentFormationSource,
        project_id: projectId,
      };
      const responseData = await createAssessment(data);

      setAssessmentFormationId(responseData.id);
      setAssessmentFormationDetails({...assessmentFormationDetails,  ...responseData.details});

      router.push(`/project/${projectId}/assessment/${responseData.id}/assessment-mode`);
    } catch (error) {
      console.error(error);
    } finally {
      setIsActiveApiCall(false);
    }
  };

  const updateSummary = () => {
    const current_active_competencies = new Set(
      tableData
        .filter((item) => item.add_to_test)
        .map((item) => item.competency),
    ).size;

    const current_active_sub_competencies = tableData.filter(
      (item) => item.add_to_test,
    ).length;

    const current_total_questions = tableData
      .filter((row) => row.add_to_test)
      .reduce((sum, row) => sum + (row?.questions?.length || row?.question_ids?.length), 0);

    const current_total_estimated_duration = current_total_questions;
    setSummary({
      total_competencies: current_active_competencies,
      total_sub_competencies: current_active_sub_competencies,
      selected_sub_competencies: current_active_sub_competencies,
      total_questions: current_total_questions,
      total_estimated_duration_minutes: current_total_estimated_duration,
    });

    console.log(
      current_active_competencies,
      current_active_sub_competencies,
      current_total_questions,
      current_total_estimated_duration,
    );
  };

  useEffect(() => {
    updateSummary();
  }, [tableData]);

  useEffect(() => {
    if (!assessmentFormationDetails) {
      router.replace('/dashboard');
    }
  }, [assessmentFormationDetails, router]);

  if (!assessmentFormationDetails) {
    return null;
  }

  console.log("Assessment details: ", assessmentFormationDetails);

  return (
    <div className={classes.container}>
      {/* Header Row */}
      <div className={classes.headerRow}>
        <div>
          <div className={classes.titleGroup}>
            <h1 className={classes.pageTitle}>Review Competencies</h1>
            <InfoIcon />
          </div>
          <div className={classes.projectTagGroup}>
            <span className={classes.projectLabel}>Project:</span>
            <span className={classes.projectTag}>
              {projectName || 'Unknown Project'}
            </span>
          </div>
        </div>
        <button
          className={classes.proceedBtn}
          disabled={isActiveApiCall}
          onClick={handleProceedClick}
        >
          Proceed
        </button>
      </div>

      <p className={classes.description}>
        {isAiGenerated
          ? 'Review the competencies and sub-competencies generated by AI before creating the assessment.'
          : 'Review the competencies and sub-competencies extracted from your uploaded file before generating the assessment.'}
      </p>

      {/* Summary Cards */}
      <div className={classes.summaryCards}>
        {/* Card 1 */}
        <div className={classes.card}>
          <div className={classes.cardIconBg}>
            <svg
              width="20"
              height="20"
              viewBox="0 0 24 24"
              fill="none"
              stroke="#A47618"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
            >
              <circle cx="12" cy="12" r="10"></circle>
              <circle cx="12" cy="12" r="6"></circle>
              <circle cx="12" cy="12" r="2"></circle>
            </svg>
          </div>
          <div className={classes.cardContent}>
            <span className={classes.cardNumber}>
              {summary?.total_competencies || 0}
            </span>
            <span className={classes.cardLabel}>competencies</span>
            <span className={classes.cardSubLabel}>{sourceSubLabel}</span>
          </div>
        </div>

        {/* Card 2 */}
        <div className={classes.card}>
          <div className={classes.cardIconBg}>
            <svg
              width="20"
              height="20"
              viewBox="0 0 24 24"
              fill="none"
              stroke="#A47618"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
            >
              <path d="M22 11.08V12a10 10 0 1 1-5.93-9.14"></path>
              <polyline points="22 4 12 14.01 9 11.01"></polyline>
            </svg>
          </div>
          <div className={classes.cardContent}>
            <span className={classes.cardNumber}>
              {summary?.total_sub_competencies || 0}
            </span>
            <span className={classes.cardLabel}>Sub-competencies</span>
            <span className={classes.cardSubLabel}>{sourceSubLabel}</span>
          </div>
        </div>

        {/* Card 3 */}
        {assessmentFormationSource ===
          assessmentFormationSourceType?.QUESTION_UPLOAD && (
          <div className={classes.card}>
            <div className={classes.cardIconBg}>
              <svg
                width="20"
                height="20"
                viewBox="0 0 24 24"
                fill="none"
                stroke="#A47618"
                strokeWidth="2"
                strokeLinecap="round"
                strokeLinejoin="round"
              >
                <circle cx="12" cy="12" r="10"></circle>
                <path d="M9.09 9a3 3 0 0 1 5.83 1c0 2-3 3-3 3"></path>
                <line x1="12" y1="17" x2="12.01" y2="17"></line>
              </svg>
            </div>
            <div className={classes.cardContent}>
              <span className={classes.cardNumber}>
                {summary?.total_questions || 0}
              </span>
              <span className={classes.cardLabel}>Total Questions</span>
              <span className={classes.cardSubLabel}>{sourceSubLabel}</span>
            </div>
          </div>
        )}

        {/* Card 4 */}
        {assessmentFormationSource ===
          assessmentFormationSourceType?.QUESTION_UPLOAD && (
          <div className={classes.card}>
            <div className={classes.cardIconBg}>
              <svg
                width="20"
                height="20"
                viewBox="0 0 24 24"
                fill="none"
                stroke="#A47618"
                strokeWidth="2"
                strokeLinecap="round"
                strokeLinejoin="round"
              >
                <circle cx="12" cy="12" r="10"></circle>
                <polyline points="12 6 12 12 16 14"></polyline>
              </svg>
            </div>
            <div className={classes.cardContent}>
              <span className={classes.cardNumber}>
                {summary?.total_estimated_duration_minutes || 0}{' '}
                <span className={classes.cardUnit}>Minutes</span>
              </span>
              <span className={classes.cardLabel}>Estimated Duration</span>
              <span className={classes.cardSubLabel}>Auto-calculated</span>
            </div>
          </div>
        )}
      </div>

      {/* Action Row */}
      {/* 
      <div className={classes.actionRow}>
        <div className={classes.saveDropdown}>
          <button className={classes.saveBtnText}>Save Competency</button>
          <div className={classes.saveBtnDivider}></div>
          <button className={classes.saveBtnIcon}>
            <svg
              width="16"
              height="16"
              viewBox="0 0 24 24"
              fill="none"
              stroke="currentColor"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
            >
              <polyline points="6 9 12 15 18 9"></polyline>
            </svg>
          </button>
        </div>
      </div>
      */}

      {/* Data Table */}
      <div className={classes['table-wrapper']}>
        <table className={classes['comp-table']}>
          <thead>
            <tr>
              <th width="5%">#</th>
              <th width="20%">
                <div className={classes['icon-align']}>
                  COMPETENCY <InfoIcon />
                </div>
              </th>
              <th width="25%">
                <div className={classes['icon-align']}>
                  SUB-COMPETENCY <InfoIcon />
                </div>
              </th>
              <th width="12%" className={classes['must-have']}>
                MUST HAVE
              </th>
              <th width="12%" className={classes['good-to-have']}>
                GOOD TO HAVE
              </th>
              <th width="12%" className={classes['icing-on-cake']}>
                ICING ON CAKE
              </th>
              <th width="10%" className={classes['center-col']}>
                <div
                  className={classes['icon-align']}
                  style={{ justifyContent: 'center' }}
                >
                  QUESTIONS <InfoIcon />
                </div>
              </th>
              <th width="10%" className={classes['center-col']}>
                ADD TO TEST
              </th>
            </tr>
          </thead>
          <tbody>
            {tableData.map((row, idx) => (
              <tr key={idx}>
                <td className={classes['id-col']}>
                  <div className={classes['ai-icon-part']}>
                    {idx + 1}
                    {assessmentFormationSource &&
                      assessmentFormationSource !==
                        assessmentFormationSourceType.QUESTION_UPLOAD && (
                        <div className={classes['ai-icon']}>
                          <Image src={aiInterView} alt="" />
                        </div>
                      )}
                  </div>
                </td>
                <td>
                  <div className={classes['icon-align']}>
                    {row.competency} <InfoIcon />
                  </div>
                </td>
                <td>
                  <div className={classes['icon-align']}>
                    {row.sub_competency} <InfoIcon />
                  </div>
                </td>

                {/* Must Have Radio */}
                <td className={classes['center-col']}>
                  <div
                    className={`${classes['custom-radio']} ${row.priority === 'must have' ? classes['radio-red'] : ''}`}
                    onClick={() => handleLevelChange(idx, 'must have')}
                  ></div>
                </td>

                {/* Good To Have Radio */}
                <td className={classes['center-col']}>
                  <div
                    className={`${classes['custom-radio']} ${row.priority === 'good to have' ? classes['radio-gold'] : ''}`}
                    onClick={() => handleLevelChange(idx, 'good to have')}
                  ></div>
                </td>

                {/* Icing On Cake Radio */}
                <td className={classes['center-col']}>
                  <div
                    className={`${classes['custom-radio']} ${row.priority === 'icing on the cake' ? classes['radio-green'] : ''}`}
                    onClick={() => handleLevelChange(idx, 'icing on the cake')}
                  ></div>
                </td>

                {/* Questions */}
                <td className={classes['center-col']}>
                  <div className={classes['question-badge']}>
                    {row?.questions_count || row?.questions?.length || row?.question_ids?.length  || 3}
                  </div>
                </td>

                {/* Add to Test Toggle & Menu */}
                <td>
                  <div className={classes['action-col']}>
                    <div
                      className={`${classes['toggle-switch']} ${row.add_to_test ? classes['toggle-on'] : classes['toggle-off']}`}
                      onClick={() => handleToggleActive(idx)}
                    >
                      <div className={classes['toggle-knob']}></div>
                    </div>
                    {/* Ellipsis Menu */}
                    <svg
                      className={classes.dots}
                      width="16"
                      height="16"
                      viewBox="0 0 24 24"
                      fill="none"
                      stroke="currentColor"
                      strokeWidth="2"
                      strokeLinecap="round"
                      strokeLinejoin="round"
                    >
                      <circle cx="12" cy="12" r="1"></circle>
                      <circle cx="12" cy="5" r="1"></circle>
                      <circle cx="12" cy="19" r="1"></circle>
                    </svg>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
};

export default ReviewCompetencies;
